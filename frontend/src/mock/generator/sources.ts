/**
 * Fictional data sources. Every name is invented and every URL uses the reserved
 * example.org domain, so nothing here can be mistaken for a real organisation.
 */

export interface SourceSeed {
  source: Source;
  /** 'global' or the regions this source covers. */
  scope: 'global' | (typeof REGIONS)[number][];
}

const S = (
  id: string,
  name: string,
  kind: Source['kind'],
  evidenceKind: Source['evidenceKind'],
  organisation: string,
  cadence: string,
  reliabilityNote: string,
  scope: SourceSeed['scope'],
  licenceNote = 'Fictional demo source: no licence applies.',
): SourceSeed => ({
  source: {
    id,
    name,
    kind,
    evidenceKind,
    organisation,
    cadence,
    licenceNote,
    reliabilityNote,
    url: `https://example.org/hazewatch-demo/sources/${id}`,
  },
  scope,
});

