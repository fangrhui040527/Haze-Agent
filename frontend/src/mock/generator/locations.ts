import type { FireInfo, Location } from '../../shared/types/domain.ts';

/**
 * Demo locations. The demo focuses on the Southeast Asian haze belt:
 *   1. Malaysia (primary)  2. Indonesia (where most of the fire smoke starts)
 *   3. neighbours hit by the same smoke (Singapore, Brunei, southern Thailand)
 *   4. the rest of Southeast Asia (Mekong dry-season burning).
 * Places on other continents are kept for the "worldwide" coverage option only.
 * Coordinates and time zones are real; everything about air quality is invented.
 * Add a location by adding one entry below; the generator picks it up automatically.
 */

export interface LocationProfile {
  /** Typical PM2.5 (µg/m³) the generator centres on. Fictional. */
  basePm25: number;
  /** Main land type for fire hotspots nearby, or null if fires are rare in the demo. */
  fireLand: FireInfo['landType'] | null;
  /** What usually drives haze here (used in text). */
  driver: string;
  /** Sub-areas used in community reports. */
  districts: string[];
}

export interface LocationSeed {
  location: Location;
  profile: LocationProfile;
}

const L = (
  id: string,
  name: string,
  region: string,
  country: string,
  countryCode: string,
  lat: number,
  lon: number,
  timeZone: string,
  aqiStandard: string,
  populationBand: Location['populationBand'],
  profile: LocationProfile,
): LocationSeed => ({
  location: {
    id,
    name,
    region,
    country,
    countryCode,
    lat,
    lon,
    timeZone,
    aqiStandard,
    populationBand,
  },
  profile,
});

