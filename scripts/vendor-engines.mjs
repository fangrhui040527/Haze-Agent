import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import ts from 'typescript';
import {
  repositoryRoot,
  resolveInside,
  sha256,
  verifySources,
  verifyWorkflowPins,
} from './engine-sources.mjs';

const manifest = await verifySources();
await verifyWorkflowPins();
const vendorRoot = resolveInside(repositoryRoot, 'vendor/meterless');
// This absolute, checked path is the generated output owned by this script.
await rm(vendorRoot, { recursive: true, force: true });
for (const source of Object.values(manifest.sources)) {
  for (const relative of Object.keys(source.files)) {
    const output = resolveInside(
      repositoryRoot,
      `${source.vendor_path}/${relative}`,
    );
    await mkdir(path.dirname(output), { recursive: true });
    await copyFile(
      resolveInside(repositoryRoot, `${source.source_path}/${relative}`),
      output,
    );
  }
}

// Replace the starter's floating degit setup with a local copy of the pinned reference.
const hmem = manifest.sources.hmem;
const starter = manifest.sources.starter;
const bundledHmem = path.posix.dirname(path.posix.dirname(hmem.entrypoint));
for (const relative of Object.keys(hmem.files).filter((file) =>
  file.startsWith('reference/'),
)) {
  const output = resolveInside(
    repositoryRoot,
    `${bundledHmem}/${relative.slice('reference/'.length)}`,
  );
  await mkdir(path.dirname(output), { recursive: true });
  await copyFile(
    resolveInside(repositoryRoot, `${hmem.source_path}/${relative}`),
    output,
  );
}
await copyFile(
  resolveInside(repositoryRoot, `${hmem.source_path}/LICENSE`),
  path.join(repositoryRoot, bundledHmem, 'LICENSE'),
);

const trees = [
  ...Object.values(manifest.sources).map((source) => source.vendor_path),
  bundledHmem,
];
for (const tree of trees) {
  const source =
    tree === bundledHmem
      ? hmem
      : Object.values(manifest.sources).find(
          (item) => item.vendor_path === tree,
        );
  const files =
    tree === bundledHmem
      ? Object.keys(hmem.files)
          .filter((file) => file.startsWith('reference/'))
          .map((file) => file.slice('reference/'.length))
      : Object.keys(source.files);
  for (const relative of files.filter((file) => file.endsWith('.ts'))) {
    const input = resolveInside(repositoryRoot, `${tree}/${relative}`);
    let content = await readFile(input, 'utf8');
    if (tree === starter.vendor_path && relative === 'src/engine.ts') {
      // The upstream loader constructs filenames at runtime. TypeScript cannot
      // rewrite those string literals, so adapt only the generated JS loader.
      content = content.replaceAll('"index.ts"', '"index.js"');
    }
    const result = ts.transpileModule(content, {
      fileName: input,
      reportDiagnostics: true,
      compilerOptions: {
        target: ts.ScriptTarget.ES2024,
        module: ts.ModuleKind.ESNext,
        rewriteRelativeImportExtensions: true,
        newLine: ts.NewLineKind.LineFeed,
      },
    });
    const errors =
      result.diagnostics?.filter(
        (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
      ) ?? [];
    if (errors.length)
      throw new Error(
        ts.formatDiagnosticsWithColorAndContext(errors, {
          getCanonicalFileName: (file) => file,
          getCurrentDirectory: () => repositoryRoot,
          getNewLine: () => '\n',
        }),
      );
    const banner =
      '// Generated by Haze from pinned Meterless Apache-2.0 source; see LICENSE and THIRD_PARTY_NOTICES.md.\n';
    await writeFile(input.slice(0, -3) + '.js', banner + result.outputText);
  }
}

const loadedImplementations = {};
for (const [name, source] of Object.entries(manifest.sources)) {
  loadedImplementations[name] = {
    revision: source.revision,
    source_sha256: source.sha256,
    entrypoint: source.entrypoint,
    entrypoint_sha256: sha256(
      await readFile(resolveInside(repositoryRoot, source.entrypoint)),
    ),
  };
}
await writeFile(
  path.join(repositoryRoot, 'vendor/engine_sources.json'),
  JSON.stringify(
    {
      ...manifest,
      build: {
        typescript: ts.version,
        loaded_implementations: loadedImplementations,
      },
    },
    null,
    2,
  ) + '\n',
);
console.log(
  `Vendored pinned starter, H-MEM and separate World Model (${hmem.revision}).`,
);
