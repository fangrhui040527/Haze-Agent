import { z } from 'zod';
import {
  artifactRefSchema,
  type Artifact,
  type ArtifactRef,
} from './artifacts.js';
import { identifierSchema } from './common.js';

const text = z.string().trim().min(1).max(4096);
const refs = z.array(artifactRefSchema).max(16);
const ids = z.array(z.uuid()).max(32);
const hash = z.string().regex(/^[a-f0-9]{64}$/);
const timestamp = z.iso.datetime({ offset: true });
const method = z.strictObject({
  id: identifierSchema,
  version: identifierSchema,
});
export const EVALUATION_COMPARISON_METHOD =
  'reduction.external-residual-comparison.v1';
export const evaluationDecimalSchema = z
  .string()
  .max(33)
  .regex(/^(?:0|-?(?:[1-9]\d*|0\.\d*[1-9]|[1-9]\d*\.\d*[1-9]))$/)
  .refine(
    (value) =>
      value.replace(/^-/, '').replace('.', '').replace(/^0+/, '').length <=
        18 && (value.split('.')[1]?.length ?? 0) <= 12,
    'At most 18 significant digits and 12 fractional places.',
  );
const resultDecimal = z
  .string()
  .max(142)
  .regex(/^(?:0|-?(?:[1-9]\d*|0\.\d*[1-9]|[1-9]\d*\.\d*[1-9]))$/);
const dateWindow = z
  .strictObject({ start: z.iso.date(), end: z.iso.date() })
  .refine((value) => value.start <= value.end, 'Period must be ordered.');
export const evaluationScopeSchema = z.strictObject({
  endpoint: text,
  unit: text,
  population: text,
  geography: text,
  pollutant: text,
  period: dateWindow,
  coverage: text,
  missingness: text,
  exclusions: z.array(text).max(64),
});
const targetFraction = evaluationDecimalSchema.refine(
  (value) =>
    value !== '0' &&
    !value.startsWith('-') &&
    (value === '1' || value.startsWith('0.')),
  'Target fraction must be greater than zero and at most one.',
);
export const evaluationCriterionSchema = z.strictObject({
  kind: z.enum(['point_estimate', 'uncertainty_bound', 'probability']),
  interpretation: text,
  dependence_assumptions: z.array(text).max(16),
});
const design = z.strictObject({
  ...method.shape,
  identification: z.enum([
    'externally_reviewed_comparative',
    'before_after_only',
    'unknown',
  ]),
  registered_name: text,
  description: text,
  assumptions: z.array(text).max(16),
  requires_independent_delivery_verification: z.boolean(),
});
const protocolBinding = z.strictObject({
  analysis_basis: z.enum([
    'original_registered',
    'prospectively_amended',
    'exploratory',
  ]),
  registration_id: z.uuid(),
  protocol_ref: artifactRefSchema,
  amendment_record_ids: ids,
});
const deliveryBinding = z.strictObject({
  action_record_ids: ids,
  deviation_record_ids: ids,
  verification_record_ids: ids,
  accounted_deviation_record_ids: ids,
  rules: z.array(method).max(16),
});
const authors = z
  .array(z.strictObject({ name: text, role: text }))
  .min(1)
  .max(16);
const registeredTarget = z.strictObject({
  fraction: targetFraction,
  relation: z.enum(['at_least', 'greater_than']),
});
export const externalEvaluationInputSchema = z.strictObject({
  schema_version: z.literal('haze.reduction.external-evaluation-input.v1'),
  programme_id: z.uuid(),
  origin: z.enum(['synthetic', 'supplied']),
  target_sha256: hash,
  scope_sha256: hash,
  protocol: protocolBinding,
  delivery: deliveryBinding,
  source_method: method,
  design,
  scope: evaluationScopeSchema,
  comparative_estimates: z.strictObject({
    baseline: evaluationDecimalSchema.nullable(),
    intervention: evaluationDecimalSchema.nullable(),
  }),
  criterion: evaluationCriterionSchema,
  registered_target: registeredTarget,
  report_refs: refs,
  data_refs: refs,
  external_review_refs: refs,
  expected_output_refs: refs,
  authors,
  uncertainty_interpretation: text,
  material_limitations: z.array(text).max(32),
});
const numericalResult = {
  baseline_damage: resultDecimal.nullable(),
  intervention_damage: resultDecimal.nullable(),
  absolute_reduction: resultDecimal.nullable(),
  relative_reduction: z
    .strictObject({ numerator: resultDecimal, denominator: resultDecimal })
    .nullable(),
  target_met: z.boolean().nullable(),
};
/** Expected outputs are separately supplied original evidence, never generated by the checking run. */
export const externalEvaluationExpectedOutputSchema = z.strictObject({
  schema_version: z.literal('haze.reduction.external-expected-output.v1'),
  programme_id: z.uuid(),
  origin: z.enum(['synthetic', 'supplied']),
  target_sha256: hash,
  scope_sha256: hash,
  source_method: method,
  design: method,
  criterion: evaluationCriterionSchema.shape.kind,
  ...numericalResult,
  prepared_by: text,
  evidence: refs,
});
export const externalEvaluationResultSchema = z.strictObject({
  schema_version: z.literal('haze.reduction.external-evaluation.v1'),
  programme_id: z.uuid(),
  input_ref: artifactRefSchema,
  dossier_ref: artifactRefSchema.nullable(),
  method_id: z.literal(EVALUATION_COMPARISON_METHOD),
  method_version: z.literal('1'),
  source_method: method,
  design,
  target_sha256: hash,
  scope_sha256: hash,
  protocol: protocolBinding,
  delivery: deliveryBinding,
  scope: evaluationScopeSchema,
  criterion: evaluationCriterionSchema,
  registered_target: registeredTarget,
  original_estimates: externalEvaluationInputSchema.shape.comparative_estimates,
  status: z.enum(['supported', 'incompatible', 'gap']),
  reasons: z.array(text).max(64),
  origin: z.enum(['synthetic', 'supplied', 'unknown']),
  ...numericalResult,
  reproduced: z.array(text).max(16),
  inspected: z.array(text).max(16),
  externally_calculated: z.array(text).max(16),
  uncertainty_interpretation: text,
  material_limitations: z.array(text).max(32),
  limitations: z.array(text).max(32),
  scientific_qualification: z.literal('unqualified'),
  achieved_reduction: z.literal(false),
});
export const evaluationLearningSchema = z.strictObject({
  schema_version: z.literal('haze.reduction.evaluation-learning.v1'),
  programme_id: z.uuid(),
  input_ref: artifactRefSchema,
  target_sha256: hash,
  scope_sha256: hash,
  protocol_ref: artifactRefSchema,
  origin: z.enum(['synthetic', 'supplied', 'unknown']),
  outcome: z.enum([
    'point_estimate_meets',
    'point_estimate_below',
    'insufficient_evidence',
  ]),
  lessons: z.array(text).max(16),
  next_requirements: z.array(text).max(64),
  evidence: z.array(artifactRefSchema).max(96),
  publication: z.literal('not_published'),
  scientific_qualification: z.literal('unqualified'),
  achieved_reduction: z.literal(false),
});
export const scientificQualificationDossierSchema = z.strictObject({
  schema_version: z.literal(
    'haze.reduction.scientific-qualification-dossier.v1',
  ),
  programme_id: z.uuid(),
  origin: z.enum(['synthetic', 'supplied']),
  evaluation_input_ref: artifactRefSchema,
  target_sha256: hash,
  scope_sha256: hash,
  source_method: method,
  design,
  scope: evaluationScopeSchema,
  protocol: protocolBinding,
  delivery: deliveryBinding,
  criterion: evaluationCriterionSchema,
  intended_use: z.literal('this_programme_damage_target_evaluation'),
  reference_case: z.strictObject({
    name: text,
    description: text,
    evidence: refs,
  }),
  scientific_owner: text,
  authors,
  reviewer: z.strictObject({
    name: text,
    role: text,
    independent: z.boolean(),
    conflicts: z.enum(['none_declared', 'resolved', 'unresolved']),
    reviewed_at: timestamp,
  }),
  applicability: z.strictObject({
    decision: z.enum(['applicable', 'conditional', 'inapplicable']),
    statement: text,
    prerequisites: z.array(text).max(32),
    unresolved_material_objections: z.array(text).max(32),
  }),
  decision: z.enum(['qualified', 'conditional', 'unqualified', 'withdrawn']),
  reasons: z.array(text).max(32),
  report_refs: refs,
  data_refs: refs,
  external_review_refs: refs,
  expected_output_refs: refs,
  evidence: refs,
  material_limitations: z.array(text).max(32),
  uncertainty_interpretation: text,
});
export const evaluationTechnicalReviewSchema = z.strictObject({
  schema_version: z.literal('haze.reduction.evaluation-review.v1'),
  programme_id: z.uuid(),
  input_ref: artifactRefSchema,
  dossier_ref: artifactRefSchema.nullable(),
  reviewed_artifacts: z.array(artifactRefSchema).min(2).max(16),
  reviewer: z.strictObject({
    assignment_id: z.uuid(),
    revision: z.number().int().positive(),
  }),
  verdict: z.enum(['supported', 'rejected', 'needs_review']),
  checks: z
    .array(
      z.strictObject({
        code: identifierSchema,
        passed: z.boolean(),
        detail: text,
      }),
    )
    .max(64),
  findings: z.array(text).max(64),
  qualification_check: z.strictObject({
    status: z.enum(['complete', 'incomplete', 'not_supplied']),
    reasons: z.array(text).max(64),
  }),
  reproduced: z.array(text).max(16),
  limitations: z.array(text).max(32),
  scientific_qualification: z.literal('unqualified'),
  achieved_reduction: z.literal(false),
});
export const evaluationQualificationRecordSchema = z.strictObject({
  kind: z.literal('evaluation_qualification'),
  decision: z.enum(['qualified', 'conditional', 'unqualified', 'withdrawn']),
  result_ref: artifactRefSchema,
  technical_review_ref: artifactRefSchema,
  dossier_ref: artifactRefSchema,
  adopted_by: text,
  attested_at: timestamp,
  reason: text,
  supersedes_record_id: z.uuid().nullable(),
});
export const evaluationObjectionRecordSchema = z.strictObject({
  kind: z.literal('evaluation_objection'),
  result_ref: artifactRefSchema,
  severity: z.enum(['material', 'minor']),
  status: z.enum(['open', 'resolved']),
  description: text,
  evidence: refs,
  resolves_record_id: z.uuid().nullable(),
});
export const evaluationRecordBodySchema = z.discriminatedUnion('kind', [
  evaluationQualificationRecordSchema,
  evaluationObjectionRecordSchema,
]);
export const evaluationTaskViewSchema = z.strictObject({
  task_id: z.uuid(),
  run_id: z.uuid(),
  objective_revision: z.number().int().positive(),
  state: z.enum([
    'current',
    'historical',
    'stale',
    'unavailable',
    'evidence_gap',
  ]),
  result: z
    .strictObject({
      artifact: artifactRefSchema,
      value: externalEvaluationResultSchema,
    })
    .nullable(),
  learning: z
    .strictObject({
      artifact: artifactRefSchema,
      value: evaluationLearningSchema,
    })
    .nullable(),
  review: z
    .strictObject({
      artifact: artifactRefSchema,
      value: evaluationTechnicalReviewSchema,
    })
    .nullable(),
  reasons: z.array(text).max(64),
  scientific_qualification: z.literal('unqualified'),
  achieved_reduction: z.literal(false),
});
export const programmeEvaluationProjectionSchema = z.strictObject({
  current: evaluationTaskViewSchema.nullable(),
  qualification: z.strictObject({
    status: z.enum(['unqualified', 'conditional', 'qualified', 'withdrawn']),
    record_id: z.uuid().nullable(),
    dossier_ref: artifactRefSchema.nullable(),
    adopted_by: text.nullable(),
    human_attestation: z.literal(true),
    reasons: z.array(text).max(64),
  }),
  claim: z.strictObject({
    eligible: z.boolean(),
    label: z.enum([
      'external_evaluation_supports_registered_target',
      'point_estimate_meets_target',
      'point_estimate_below_target',
      'insufficient_evidence',
    ]),
    point_estimate: z.enum(['meets', 'below', 'unavailable']),
    reasons: z.array(text).max(64),
    reproduction_limits: z.array(text).max(32),
  }),
  qualifications: z
    .array(
      z.strictObject({
        record_id: z.uuid(),
        decision: evaluationQualificationRecordSchema.shape.decision,
        currency: z.enum(['current', 'stale', 'superseded']),
        reasons: z.array(text).max(64),
      }),
    )
    .max(32),
  objections: z
    .array(
      z.strictObject({
        record_id: z.uuid(),
        unresolved: z.boolean(),
        material: z.boolean(),
        reasons: z.array(text).max(32),
      }),
    )
    .max(32),
  reasons: z.array(text).max(64),
  operational_release: z.enum([
    'gated_pending_non_synthetic_trace',
    'qualified_reference_trace_supported',
  ]),
  achieved_reduction: z.boolean(),
});
export type ExternalEvaluationInput = z.infer<
  typeof externalEvaluationInputSchema
>;
export type ExternalEvaluationResult = z.infer<
  typeof externalEvaluationResultSchema
>;
export type ExternalEvaluationExpectedOutput = z.infer<
  typeof externalEvaluationExpectedOutputSchema
>;
export type EvaluationLearning = z.infer<typeof evaluationLearningSchema>;
export type EvaluationTechnicalReview = z.infer<
  typeof evaluationTechnicalReviewSchema
>;
export type ScientificQualificationDossier = z.infer<
  typeof scientificQualificationDossierSchema
>;
export type EvaluationRecordBody = z.infer<typeof evaluationRecordBodySchema>;
export type EvaluationTaskView = z.infer<typeof evaluationTaskViewSchema>;
export type ProgrammeEvaluationProjection = z.infer<
  typeof programmeEvaluationProjectionSchema
>;
export interface EvaluationMethodContext {
  programme_id: string;
  input_ref: ArtifactRef;
  dossier_ref: ArtifactRef | null;
  target: {
    scope: z.infer<typeof evaluationScopeSchema>;
    target_fraction: string;
    relation: 'at_least' | 'greater_than';
    comparator: string;
    intervention: string;
    assessment_rule: 'point_estimate';
  };
  target_sha256: string;
  scope_sha256: string;
  registration_id: string | null;
  analysis_basis:
    'original_registered' | 'prospectively_amended' | 'exploratory';
  protocol_ref: ArtifactRef | null;
  amendment_record_ids: readonly string[];
  delivery: {
    action_record_ids: readonly string[];
    confirmed_action_record_ids: readonly string[];
    deviation_record_ids: readonly string[];
    unresolved_material_deviation_record_ids: readonly string[];
    verification_record_ids: readonly string[];
    rules: readonly { id: string; version: string }[];
  };
  evidence: readonly Artifact[];
  supporting_refs?: readonly ArtifactRef[];
  gate_reasons?: readonly string[];
  expectedScientificOwner?: string | null;
}
